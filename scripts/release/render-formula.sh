#!/usr/bin/env bash
# Render Formula/wtree.rb for KKamJi98/homebrew-tap from the release checksums.
#
# usage: render-formula.sh <version> <dist-dir>
#   <dist-dir> holds wt-<version>-<target>.tar.gz.sha256 for the four
#   macOS/Linux targets. The formula is written to stdout.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <dist-dir>" >&2
  exit 2
fi

version="$1"
dist="$2"

if [[ ! "${version}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "version must look like 1.2.3, got '${version}'" >&2
  exit 2
fi

base="https://github.com/KKamJi98/wtree/releases/download/v${version}"

sha() {
  local file="${dist}/wt-${version}-$1.tar.gz.sha256"
  local sum
  sum="$(cut -d ' ' -f 1 "${file}")"
  if [[ ! "${sum}" =~ ^[0-9a-f]{64}$ ]]; then
    echo "bad checksum in ${file}" >&2
    exit 1
  fi
  printf '%s' "${sum}"
}

# Read every checksum before rendering: a failure inside the heredoc's $(...)
# would not stop the script, and the formula would carry an empty sha256.
sha_mac_arm="$(sha aarch64-apple-darwin)"
sha_mac_intel="$(sha x86_64-apple-darwin)"
sha_linux_arm="$(sha aarch64-unknown-linux-musl)"
sha_linux_intel="$(sha x86_64-unknown-linux-musl)"

cat <<EOF
# Generated by KKamJi98/wtree .github/workflows/release.yml. Do not edit here.
class Wtree < Formula
  desc "Manage git worktree repositories: fetch, pull and status across worktrees"
  homepage "https://github.com/KKamJi98/wtree"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/wt-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${sha_mac_arm}"
    end
    on_intel do
      url "${base}/wt-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${sha_mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/wt-${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_arm}"
    end
    on_intel do
      url "${base}/wt-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_intel}"
    end
  end

  # Both install a binary named wt.
  conflicts_with "worktrunk", because: "both install a \`wt\` binary"
  conflicts_with "wiredtiger", because: "both install a \`wt\` binary"

  def install
    bin.install "wt"
    generate_completions_from_executable(bin/"wt", shell_parameter_format: :clap)
  end

  test do
    assert_match "wt #{version}", shell_output("#{bin}/wt --version")
  end
end
EOF
